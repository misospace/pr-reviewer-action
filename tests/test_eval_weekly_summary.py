#!/usr/bin/env python3
"""Regression tests for the weekly eval-harness summary (#715).

The scheduled summary in ``.github/workflows/eval-harness.yaml`` used to
read per-mode pass rates from ``report["modes"][mode]["pass_rate"]`` — a
structure the producer has never emitted — so every weekly summary
rendered its per-mode rates as unknown even when valid results existed.

These tests pin the actual producer → summary boundary: reports are built
with the real ``generate_report`` from ``scripts/eval_harness.py`` (and,
for the CLI tests, committed fixtures *generated by* that producer), then
fed to ``scripts/eval_weekly_summary.py``. The tests never mock an
invented report shape.

Covered behavior:
  - pass rates render from the canonical ``mode_summary`` blocks;
  - legacy/missing fields degrade explicitly (loud missing-block line,
    ``n/a`` for unscored modes, unreadable rates called out) rather than
    silently reading the wrong structure;
  - rendering is deterministic (fixed stamp → byte-identical output);
  - the #711 all-runs-error behavior is preserved (summary written, exit
    code 1 after the write).
"""

