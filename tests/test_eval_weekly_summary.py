class TestLegacyDegradation:
    def test_mode_without_summary_block_is_loud(self):
        """A modes_tested entry with no mode_summary block names the gap."""
        report = {
            "metadata": {"modes_tested": ["native_loop", "ghost_mode"],
                         "total_prs": 1, "total_runs": 1, "completed_runs": 1},
            "mode_summary": {"native_loop": {"capability_pass_rate": 1.0,
                                             "successful_runs": 1}},
        }

        body = render_weekly_summary(report, STAMP)

        assert "- ⚠️ **ghost_mode** no per-mode summary block in report" in body
        assert "- ✅ **native_loop** pass_rate=1.0" in body

    def test_legacy_pass_rate_field_is_honoured(self):
        """An explicit block-level ``pass_rate`` (older field name) is used."""
        report = {
            "metadata": {"modes_tested": ["native_loop"], "total_prs": 1},
            "mode_summary": {"native_loop": {"pass_rate": 0.8,
                                             "successful_runs": 4}},
        }

        body = render_weekly_summary(report, STAMP)

        assert "- ⚠️ **native_loop** pass_rate=0.8" in body

    def test_pre_711_report_falls_back_to_successful_runs(self):
        """A pre-#711 report (no metadata.completed_runs) still counts.

        Mirrors count_completed_runs in scripts/eval_harness.py.
        """
        report = {
            "metadata": {"modes_tested": ["tools_off", "native_loop"]},
            "mode_summary": {
                "tools_off": {"successful_runs": 3},
                "native_loop": {"successful_runs": 0},
            },
        }

        assert count_completed_runs(report) == 3
        assert all_runs_errored(report) is False
        body = render_weekly_summary(report, STAMP)
        # No total_runs in metadata → no runs-completed line at all.
        assert "Runs completed" not in body

    def test_pre_711_all_errored_report_still_fails(self):
        """The pre-#711 fallback keeps the zero-completed-runs failure."""
        report = {
            "metadata": {"modes_tested": ["native_loop"]},
            "mode_summary": {"native_loop": {"successful_runs": 0}},
        }

        assert all_runs_errored(report) is True
        body = render_weekly_summary(report, STAMP)
        assert "Every harness run errored" in body

    def test_missing_modes_tested_falls_back_to_mode_summary_keys(self):
        report = {
            "metadata": {},
            "mode_summary": {
                "tools_off": {"capability_pass_rate": None},
                "native_loop": {"capability_pass_rate": 1.0},
            },
        }

        body = render_weekly_summary(report, STAMP)

        assert "- **Modes tested:** native_loop, tools_off" in body

    def test_unreadable_pass_rate_is_called_out(self):
        report = {
            "metadata": {"modes_tested": ["native_loop"], "total_prs": 1},
            "mode_summary": {"native_loop": {"capability_pass_rate": "high"}},
        }

        body = render_weekly_summary(report, STAMP)

        assert (
            "- ❓ **native_loop** pass_rate unreadable "
            "(capability_pass_rate='high' is not a number)"
        ) in body

    def test_legacy_pr_count_alias_is_honoured(self):
        report = {
            "metadata": {"modes_tested": ["native_loop"], "pr_count": 4},
            "mode_summary": {"native_loop": {"capability_pass_rate": 1.0}},
        }

        body = render_weekly_summary(report, STAMP)

        assert "- **PRs evaluated:** 4" in body

    def test_missing_pr_count_degrades_to_na(self):
        report = {
            "metadata": {"modes_tested": ["native_loop"]},
            "mode_summary": {"native_loop": {"capability_pass_rate": 1.0}},
        }

        body = render_weekly_summary(report, STAMP)

        assert "- **PRs evaluated:** n/a" in body

    def test_regressions_read_from_mode_summary_block(self):
        """Regression data comes from the per-mode block, never elsewhere.

        Generated reports carry no regressions today; the field is honoured
        only when a report explicitly provides it inside mode_summary.
        """
        report = {
            "metadata": {"modes_tested": ["native_loop"], "total_prs": 1},
            "mode_summary": {
                "native_loop": {
                    "capability_pass_rate": 0.9,
                    "regressions": ["cited_matrix_in_review"],
                },
            },
        }

        body = render_weekly_summary(report, STAMP)

        assert "  - regressions: cited_matrix_in_review" in body
        assert (
            "> ⚠️ One or more modes show regressions vs. last weekly baseline."
        ) in body

    def test_no_regressions_field_never_claims_regressions(self):
        """The canonical shape has no regressions; none may be invented."""
        report = {
            "metadata": {"modes_tested": ["native_loop"], "total_prs": 1},
            "mode_summary": {"native_loop": {"capability_pass_rate": 0.5}},
        }

        body = render_weekly_summary(report, STAMP)

        assert "regressions" not in body

    def test_malformed_regressions_field_is_called_out(self):
        report = {
            "metadata": {"modes_tested": ["native_loop"], "total_prs": 1},
            "mode_summary": {
                "native_loop": {"capability_pass_rate": 1.0,
                                "regressions": "cited_matrix_in_review"},
            },
        }

        body = render_weekly_summary(report, STAMP)

        assert "regressions: unreadable in report (expected a list)" in body
        assert "show regressions vs. last weekly baseline" not in body


