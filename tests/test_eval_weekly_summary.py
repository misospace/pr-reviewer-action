def _run_cli(*argv: str) -> subprocess.CompletedProcess:
    """Run the summary CLI in an environment-deterministic way.

    A GitHub Actions runner exports ``GITHUB_STEP_SUMMARY``; inherited by
    the child, the CLI would correctly append there instead of printing to
    stdout, breaking the stdout-facing assertions. Strip it here — the
    real append behavior has its own explicit test below.
    """
    env = dict(os.environ)
    env.pop("GITHUB_STEP_SUMMARY", None)
    return subprocess.run(
        [sys.executable, str(_SCRIPTS_DIR / "eval_weekly_summary.py"), *argv],
        capture_output=True, text=True, cwd=_ROOT, check=False, env=env,
    )


class TestCliFixtures:
    """The committed fixtures were generated by scripts/eval_harness.py's
    generate_report (10 native_loop + 10 tools_off runs over the #7462
    evidence scenario, plus a findings-only PR) — not hand-authored — so
    the CLI is exercised against a real producer-shaped report."""

    def test_agentic_fixture_renders_real_rates(self):
        result = _run_cli(
            "--report", str(FIXTURES / "eval-report-agentic.json"),
            "--stamp", STAMP,
        )
        assert result.returncode == 0, result.stderr

        # The CLI prints the body when GITHUB_STEP_SUMMARY is unset.
        body = result.stdout

        assert "## Weekly eval-harness regression summary" in body
        assert f"_Run: {STAMP}_" in body
        assert "- **Modes tested:** native_loop, tools_off" in body
        assert "- **PRs evaluated:** 2" in body
        assert "- **Runs completed:** 21/21" in body
        assert "- ⚠️ **native_loop** pass_rate=0.7" in body
        assert "- ⚠️ **tools_off** pass_rate=0.0" in body
        assert "pass_rate=None" not in body
        assert "Every harness run errored" not in body

    def test_agentic_fixture_is_deterministic(self):
        out_a = _run_cli(
            "--report", str(FIXTURES / "eval-report-agentic.json"),
            "--stamp", STAMP,
        ).stdout
        out_b = _run_cli(
            "--report", str(FIXTURES / "eval-report-agentic.json"),
            "--stamp", STAMP,
        ).stdout

        assert out_a == out_b

    def test_all_errored_fixture_writes_summary_then_fails(self):
        result = _run_cli(
            "--report", str(FIXTURES / "eval-report-all-errored.json"),
            "--stamp", STAMP,
        )

        # The #711 contract: exit 1, but only after the summary body was
        # produced (here: printed, since GITHUB_STEP_SUMMARY is unset).
        assert result.returncode == 1
        body = result.stdout
        assert "## Weekly eval-harness regression summary" in body
        assert "- **Runs completed:** 0/20" in body
        assert (
            "> ❌ Every harness run errored; no pass rates exist. "
            "Failing the job (issue #711)."
        ) in body

    def test_missing_report_is_a_skip_not_a_failure(self, tmp_path: Path):
        result = _run_cli("--report", str(tmp_path / "absent.json"))

        assert result.returncode == 0
        assert "skipping summary" in result.stdout

    def test_step_summary_env_is_appended(self, tmp_path: Path):
        summary_file = tmp_path / "step-summary.md"
        summary_file.write_text("existing\n", encoding="utf-8")

        result = subprocess.run(
            [sys.executable, str(_SCRIPTS_DIR / "eval_weekly_summary.py"),
             "--report", str(FIXTURES / "eval-report-agentic.json"),
             "--stamp", STAMP],
            capture_output=True, text=True, cwd=_ROOT, check=False,
            env={
                "GITHUB_STEP_SUMMARY": str(summary_file),
                "PATH": "/usr/bin:/bin:/usr/local/bin",
            },
        )

        assert result.returncode == 0, result.stderr
        appended = summary_file.read_text(encoding="utf-8")
        assert appended.startswith("existing\n")
        assert "## Weekly eval-harness regression summary" in appended


class TestPostIssueArgument:
    """``--post-issue NUMBER`` is authoritative for the tracking comment."""

    def test_argument_drives_the_comment_url(self, tmp_path, monkeypatch):
        """The supplied issue number reaches the posted comment URL."""
        captured: dict[str, object] = {}

        def fake_urlopen(request, timeout=None):
            captured["url"] = request.full_url
            captured["body"] = json.loads(request.data.decode("utf-8"))["body"]
            return io.BytesIO(b"{}")

        monkeypatch.setattr("urllib.request.urlopen", fake_urlopen)
        monkeypatch.setenv("GITHUB_TOKEN", "test-token")
        monkeypatch.setenv("GITHUB_REPOSITORY", "misospace/pr-reviewer-action")
        monkeypatch.setenv("GITHUB_STEP_SUMMARY", str(tmp_path / "summary.md"))

        rc = eval_weekly_summary.main([
            "--report", str(FIXTURES / "eval-report-agentic.json"),
            "--stamp", STAMP,
            "--post-issue", "715",
        ])

        assert rc == 0
        assert captured["url"] == (
            "https://api.github.com/repos/misospace/pr-reviewer-action"
            "/issues/715/comments"
        )
        assert "## Weekly eval-harness regression summary" in captured["body"]

    def test_workflow_contract_targets_the_tracking_issue(self, tmp_path, monkeypatch):
        """The scheduled sweep's --post-issue 472 hits the #472 issue."""
        captured: dict[str, object] = {}

        def fake_urlopen(request, timeout=None):
            captured["url"] = request.full_url
            return io.BytesIO(b"{}")

        monkeypatch.setattr("urllib.request.urlopen", fake_urlopen)
        monkeypatch.setenv("GITHUB_TOKEN", "test-token")
        monkeypatch.setenv("GITHUB_REPOSITORY", "misospace/pr-reviewer-action")
        monkeypatch.setenv("GITHUB_STEP_SUMMARY", str(tmp_path / "summary.md"))

        rc = eval_weekly_summary.main([
            "--report", str(FIXTURES / "eval-report-agentic.json"),
            "--stamp", STAMP,
            "--post-issue", "472",
        ])

        assert rc == 0
        assert captured["url"].endswith("/issues/472/comments")

    def test_skips_gracefully_without_credentials(self, tmp_path, monkeypatch, capsys):
        """No token/repo env → best-effort skip, never a crash."""
        monkeypatch.delenv("GITHUB_TOKEN", raising=False)
        monkeypatch.delenv("GITHUB_REPOSITORY", raising=False)
        monkeypatch.setenv("GITHUB_STEP_SUMMARY", str(tmp_path / "summary.md"))

        rc = eval_weekly_summary.main([
            "--report", str(FIXTURES / "eval-report-agentic.json"),
            "--stamp", STAMP,
            "--post-issue", "472",
        ])

        assert rc == 0
        assert "skipping the" in capsys.readouterr().err
