class TestAllErrored:
    def test_generated_all_errored_report_flags_and_counts_zero(self):
        errored = []
        for _ in range(3):
            bad = _chained_run()
            bad.error = "Review failed (exit 1): boom"
            bad.tool_calls = []
            bad.review_markdown = ""
            errored.append(bad)
        report = generate_report(
            [BenchmarkResult(pr_number=7462, repo_full_name="joryirving/home-ops",
                             runs=errored)],
            _agentic_corpus(),
        )

        assert all_runs_errored(report) is True
        body = render_weekly_summary(report, STAMP)
        assert (
            "> ❌ Every harness run errored; no pass rates exist. "
            "Failing the job (issue #711)."
        ) in body
        assert "- **Runs completed:** 0/3" in body
        # Errored runs are scored as failed capability checks by the
        # producer, so the canonical rate is 0.0 — the footer explains why
        # the job fails.
        assert "- ⚠️ **native_loop** pass_rate=0.0" in body

    def test_partial_failure_is_not_all_errored(self):
        runs = [_chained_run(), _chained_run()]
        bad = _chained_run()
        bad.error = "boom"
        runs.append(bad)
        report = generate_report(
            [BenchmarkResult(pr_number=7462, repo_full_name="joryirving/home-ops",
                             runs=runs)],
            _agentic_corpus(),
        )

        assert all_runs_errored(report) is False
        body = render_weekly_summary(report, STAMP)
        assert "Every harness run errored" not in body


