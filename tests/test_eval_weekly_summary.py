class TestBoundary:
    def test_renders_pass_rates_from_generated_report(self):
        """The summary shows the rates generate_report actually emits.

        10 native_loop runs, 7 close the chain → capability_pass_rate 0.7;
        a findings-only PR leaves tools_off unscored (None → explicit n/a).
        """
        runs = [_chained_run() for _ in range(7)]
        for _ in range(3):
            bad = _chained_run()
            bad.tool_calls = []
            bad.review_markdown = "approve"
            runs.append(bad)
        runs.append(ReviewRun(
            mode="tools_off", pr_number=110,
            repo_full_name="misospace/pr-reviewer-action",
        ))
        results = [
            BenchmarkResult(pr_number=7462, repo_full_name="joryirving/home-ops",
                            runs=runs[:10]),
            BenchmarkResult(pr_number=110, repo_full_name="misospace/pr-reviewer-action",
                            runs=runs[10:]),
        ]
        report = generate_report(results, _agentic_corpus())

        body = render_weekly_summary(report, STAMP)

        assert "- ⚠️ **native_loop** pass_rate=0.7" in body
        assert (
            "- ❓ **tools_off** pass_rate=n/a (no capability checks scored "
            "for this mode)"
        ) in body
        # The wrong-structure read must never come back: no line pretends a
        # rate was found when mode_summary holds none.
        assert "pass_rate=None" not in body

    def test_summary_rates_equal_mode_summary_values(self):
        """Every rendered rate equals report["mode_summary"][mode].

        Only modes listed in metadata.modes_tested are rendered — the
        producer pre-seeds untested classic modes in mode_summary with
        zero runs, and the summary must not surface them.
        """
        runs = [_chained_run() for _ in range(9)]
        bad = _chained_run()
        bad.tool_calls = []
        runs.append(bad)
        report = generate_report(
            [BenchmarkResult(pr_number=7462, repo_full_name="joryirving/home-ops",
                             runs=runs)],
            _agentic_corpus(),
        )

        body = render_weekly_summary(report, STAMP)

        # The untested classic mode must not leak into the summary.
        assert "**tools_off**" not in body
        for mode in report["metadata"]["modes_tested"]:
            block = report["mode_summary"][mode]
            rate = block["capability_pass_rate"]
            if rate is None:
                assert f"**{mode}** pass_rate=n/a" in body
            else:
                assert f"**{mode}** pass_rate={rate}" in body

    def test_below_threshold_rate_warns(self):
        """A scored rate below 0.95 renders the warning emoji."""
        runs = [_chained_run() for _ in range(1)]
        for _ in range(9):
            bad = _chained_run()
            bad.tool_calls = []
            bad.review_markdown = "approve"
            runs.append(bad)
        report = generate_report(
            [BenchmarkResult(pr_number=7462, repo_full_name="joryirving/home-ops",
                             runs=runs)],
            _agentic_corpus(),
        )
        assert report["mode_summary"]["native_loop"]["capability_pass_rate"] == 0.1

        body = render_weekly_summary(report, STAMP)

        assert "- ⚠️ **native_loop** pass_rate=0.1" in body

    def test_at_threshold_rate_passes(self):
        """Exactly 0.95 is green (>= comparison, as before #715)."""
        runs = [_chained_run() for _ in range(19)]
        bad = _chained_run()
        bad.tool_calls = []
        bad.review_markdown = "approve"
        runs.append(bad)
        report = generate_report(
            [BenchmarkResult(pr_number=7462, repo_full_name="joryirving/home-ops",
                             runs=runs)],
            _agentic_corpus(),
        )
        assert report["mode_summary"]["native_loop"]["capability_pass_rate"] == 0.95

        body = render_weekly_summary(report, STAMP)

        assert "- ✅ **native_loop** pass_rate=0.95" in body

    def test_runs_completed_line_from_generated_metadata(self):
        """The runs-completed line uses the producer's #711 metadata."""
        report = generate_report(
            [BenchmarkResult(pr_number=7462, repo_full_name="joryirving/home-ops",
                             runs=[_chained_run()])],
            _agentic_corpus(),
        )
        assert report["metadata"]["completed_runs"] == 1

        body = render_weekly_summary(report, STAMP)

        assert "- **Runs completed:** 1/1" in body
        assert "- **PRs evaluated:** 1" in body


