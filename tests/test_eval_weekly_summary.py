class TestDeterminism:
    def test_same_report_and_stamp_render_byte_identical(self):
        report = generate_report(
            [BenchmarkResult(pr_number=7462, repo_full_name="joryirving/home-ops",
                             runs=[_chained_run() for _ in range(3)])],
            _agentic_corpus(),
        )

        first = render_weekly_summary(report, STAMP)
        second = render_weekly_summary(report, STAMP)

        assert first == second

    def test_only_the_stamp_differs_between_runs(self):
        report = generate_report(
            [BenchmarkResult(pr_number=7462, repo_full_name="joryirving/home-ops",
                             runs=[_chained_run() for _ in range(3)])],
            _agentic_corpus(),
        )

        a = render_weekly_summary(report, "2026-09-21T06:00:00Z").splitlines()
        b = render_weekly_summary(report, "2026-09-28T06:00:00Z").splitlines()

        assert a[2] == "_Run: 2026-09-21T06:00:00Z_"
        assert b[2] == "_Run: 2026-09-28T06:00:00Z_"
        assert a[:2] + a[3:] == b[:2] + b[3:]


