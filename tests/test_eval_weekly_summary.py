#!/usr/bin/env python3
"""Regression tests for the weekly eval-harness summary (#715).

The scheduled summary in ``.github/workflows/eval-harness.yaml`` used to
read per-mode pass rates from ``report["modes"][mode]["pass_rate"]`` — a
structure the producer has never emitted — so every weekly summary
rendered its per-mode rates as unknown even when valid results existed.

These tests pin the actual producer → summary boundary: reports are built
with the real ``generate_report`` from ``scripts/eval_harness.py`` (and,
for the CLI tests, committed fixtures *generated by* that producer), then
fed to ``scripts/eval_weekly_summary.py``. The tests never mock an
invented report shape.

Covered behavior:
  - pass rates render from the canonical ``mode_summary`` blocks;
  - legacy/missing fields degrade explicitly (loud missing-block line,
    ``n/a`` for unscored modes, unreadable rates called out) rather than
    silently reading the wrong structure;
  - rendering is deterministic (fixed stamp → byte-identical output);
  - the #711 all-runs-error behavior is preserved (summary written, exit
    code 1 after the write).
"""

from __future__ import annotations

import io
import json
import os
import subprocess
import sys
from pathlib import Path

# Ensure scripts directory is on path for imports
_ROOT = Path(__file__).resolve().parent.parent
_SCRIPTS_DIR = _ROOT / "scripts"
if str(_SCRIPTS_DIR) not in sys.path:
    sys.path.insert(0, str(_SCRIPTS_DIR))

import eval_weekly_summary
from eval_harness import BenchmarkCorpus, BenchmarkResult, ReviewRun, generate_report
from eval_weekly_summary import (
    all_runs_errored,
    count_completed_runs,
    render_weekly_summary,
)

FIXTURES = _ROOT / "tests" / "fixtures" / "eval_weekly_summary"
STAMP = "2026-09-21T06:00:00Z"

# Mirrors the home-ops#7462 scenario from tests/test_eval_harness.py: a
# three-check expected_evidence block the native_loop must close.
TALOS_EVIDENCE = {
    "description": "chain to the support matrix and cite it",
    "checks": [
        {"id": "read_machineconfig", "type": "tool_call", "tool": "read_file",
         "args_contains": {"path": ["machineconfig"]}},
        {"id": "fetched_support_matrix", "type": "tool_call", "tool": "web_fetch",
         "args_contains": {"url": ["talos.dev", "support-matrix"]}},
        {"id": "cited_matrix_in_review", "type": "review_mentions",
         "any_of": ["support matrix", "talos.dev"]},
    ],
}


def _chained_run(mode="native_loop") -> ReviewRun:
    """A run that fully closes the Talos evidence chain."""
    return ReviewRun(
        mode=mode, pr_number=7462, repo_full_name="joryirving/home-ops",
        review_markdown="Verified against the Talos support matrix: k8s v1.36 is supported.",
        tool_calls=[
            {"tool": "read_file", "args": {"path": "talos/main/machineconfig.yaml.j2"}, "status": "ok"},
            {"tool": "web_fetch", "args": {"url": "https://www.talos.dev/v1.13/introduction/support-matrix/"}, "status": "ok"},
        ],
        tool_stop_reason="model-stopped",
    )


def _agentic_corpus() -> BenchmarkCorpus:
    return BenchmarkCorpus(prs=[
        {"number": 7462, "repo_full_name": "joryirving/home-ops",
         "url": "https://github.com/joryirving/home-ops/pull/7462",
         "known_findings": [], "expected_evidence": TALOS_EVIDENCE},
        {"number": 110, "repo_full_name": "misospace/pr-reviewer-action",
         "url": "https://github.com/misospace/pr-reviewer-action/pull/110",
         "known_findings": []},
    ])


