#!/usr/bin/env node
// #1240: builds the action-source witness INTO THE EXECUTING BUNDLE.
//
// The gate-absence boundary (#1238) decides a claim against the EXECUTING
// action's own implementation. Reading those bytes from the action's
// install directory at runtime left a filesystem TOCTOU window: the
// containment check and the read were separate steps, so a concurrent
// mutation of the tree could swap an intermediate path component between
// them and serve bytes from outside the action root. The witness is
// therefore embedded at BUILD time: the bundle IS the executing action's
// own implementation (the install tree's `src/` is not what runs), so the
// embedded bytes are revision-bound by construction and the runtime
// performs no filesystem content read at all — no check/read race can
// exist because there is no check.
//
// The registry (src/enforcement/action-gates.ts) is read through its own
// compiled module, so the embedded paths and markers are the registry's
// VALUES, not text scraped out of the file. A gate whose cited
// implementation does not contain its marker FAILS the build: a gate the
// source does not implement must never be embedded, because embedding it
// would let the boundary refute a claim with a file that proves nothing.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const REGISTRY = resolve(REPO_ROOT, "src/enforcement/action-gates.ts");
const OUTPUT = resolve(REPO_ROOT, ".v3-generated/action-source.generated.ts");
/** #1240: the same cap the runtime reader enforces on an embedded file. */
const MAX_EMBEDDED_BYTES = 1024 * 1024;

/**
 * The registry's entries, read through the registry's own compiled module.
 *
 * The module is bundled in memory (esbuild is already this repository's
 * bundler) and imported as a data URL, so the entries are the values the
 * registry actually exports — a literal's VALUE, never the raw file text.
 */
async function readRegistry() {
  const bundled = await build({
    entryPoints: [REGISTRY],
    bundle: true,
    platform: "node",
    target: "node22",
    format: "esm",
    write: false,
    logLevel: "silent",
  });
  const source = bundled.outputFiles[0].text;
  const module = await import(`data:text/javascript;base64,${Buffer.from(source, "utf8").toString("base64")}`);
  const gates = module.ACTION_GATES;
  if (!Array.isArray(gates) || gates.length === 0) {
    throw new Error(`${REGISTRY} exports no ACTION_GATES entries`);
  }
  return gates;
}

/**
 * The implementation file a gate cites, with every check that must hold
 * before its bytes may be embedded. Each failure throws: the build fails
 * closed rather than embedding a witness the registry cannot vouch for.
 */
function readImplementation(gate) {
  if (typeof gate.id !== "string" || gate.id === "") {
    throw new Error("ACTION_GATES holds an entry with no id");
  }
  const implementation = gate.implementation;
  if (typeof implementation !== "string" || implementation === "") {
    throw new Error(`gate ${gate.id} cites no implementation path`);
  }
  if (isAbsolute(implementation) || implementation.split("/").includes("..")) {
    throw new Error(`gate ${gate.id} cites a non-repo-relative implementation path: ${implementation}`);
  }
  if (!implementation.startsWith("src/")) {
    throw new Error(`gate ${gate.id} must cite the action's own source tree: ${implementation}`);
  }
  const path = resolve(REPO_ROOT, implementation);
  if (path !== REPO_ROOT && !path.startsWith(REPO_ROOT + sep)) {
    throw new Error(`gate ${gate.id} cites an implementation outside the repository: ${implementation}`);
  }
  let bytes;
  try {
    bytes = readFileSync(path);
  } catch (error) {
    throw new Error(`gate ${gate.id} cites a missing implementation file: ${implementation} (${error})`);
  }
  if (bytes.length > MAX_EMBEDDED_BYTES) {
    throw new Error(`gate ${gate.id} cites an oversize implementation file: ${implementation} (${bytes.length} bytes)`);
  }
  const text = bytes.toString("utf8");
  // The marker is the gate's proof: a file that does not carry it does
  // not implement the gate, and embedding it would let the boundary
  // refute a claim with bytes that prove nothing.
  if (typeof gate.marker !== "string" || !text.includes(gate.marker)) {
    throw new Error(`gate ${gate.id} claims marker ${JSON.stringify(gate.marker)} that ${implementation} does not contain`);
  }
  return { path: implementation, text };
}

const embedded = new Map();
for (const gate of await readRegistry()) {
  const { path, text } = readImplementation(gate);
  embedded.set(path, text);
}

const body = [
  "// Generated by scripts/generate-action-source.mjs; do not edit.",
  "// The EXECUTING action's own implementation bytes, embedded at build time:",
  "// the gate-absence witness never reads the filesystem, so no check/read",
  "// race can exist.",
  "export const ACTION_SOURCE_FILES: ReadonlyMap<string, string> = new Map([",
  ...[...embedded].map(([path, text]) => `  [${JSON.stringify(path)}, ${JSON.stringify(text)}],`),
  "]);",
  "",
].join("\n");

mkdirSync(dirname(OUTPUT), { recursive: true });
writeFileSync(OUTPUT, body);
