#!/usr/bin/env node
// Renders docs/inputs.md from contracts/action-v3.yml (the source of truth for
// every input's default and description) and scripts/docs/input-groups.json
// (which section each input is listed under).
//
//   node scripts/generate-inputs-doc.mjs           write docs/inputs.md
//   node scripts/generate-inputs-doc.mjs --check   exit 1 when it is stale
import { readFileSync, writeFileSync } from "node:fs";
import { parse } from "yaml";

const CONTRACT = "contracts/action-v3.yml";
const GROUPS = "scripts/docs/input-groups.json";
const OUTPUT = "docs/inputs.md";

// Raw JSON field names that legitimately stay snake_case in prose (mirrors
// the allowlist in tests-v3/docs-lint.test.ts).
const KEEP_SNAKE = new Set(["review_markdown", "verdict_source", "tool_calls", "analysis_engine", "review_result"]);

export function render(contract, groups) {
  const inputs = new Map(contract.inputs.map((input) => [input.id, input]));
  const renames = [...contract.inputs, ...(contract.outputs ?? [])]
    .filter((entry) => entry.v2_id && entry.v2_id.includes("_") && entry.v2_id !== entry.id && !KEEP_SNAKE.has(entry.v2_id))
    .sort((a, b) => b.v2_id.length - a.v2_id.length);
  const prose = (text) => {
    let out = String(text ?? "").replace(/\s+/g, " ").trim();
    for (const entry of renames) out = out.replace(new RegExp(`\\b${entry.v2_id}\\b`, "g"), entry.id);
    return out.replace(/\|/g, "\\|");
  };
  const fmtDefault = (input) => {
    if (input.required) return "**required**";
    if (input.default === undefined || input.default === null) return "—";
    if (input.default === "") return "empty";
    return `\`${String(input.default).replace(/\|/g, "\\|")}\``;
  };

  const listed = new Set();
  const lines = [
    "# Inputs and outputs",
    "",
    "<!-- Generated by scripts/generate-inputs-doc.mjs from contracts/action-v3.yml. Do not edit by hand. -->",
    "",
    "Only `ai-base-url` and `ai-model` must be set; every other input has a default, and the defaults are the recommended setup. Input names are kebab-case.",
    "",
    "## Inputs",
    "",
  ];
  for (const group of groups) {
    lines.push(`### ${group.title}`, "", `${group.summary.charAt(0).toUpperCase()}${group.summary.slice(1)}.`, "");
    lines.push("| Input | Default | Description |", "|-------|---------|-------------|");
    for (const id of group.inputs) {
      const input = inputs.get(id);
      if (!input) throw new Error(`${GROUPS}: unknown input '${id}'`);
      if (listed.has(id)) throw new Error(`${GROUPS}: input '${id}' is listed twice`);
      listed.add(id);
      lines.push(`| \`${id}\` | ${fmtDefault(input)} | ${prose(input.description)} |`);
    }
    lines.push("");
  }
  const unlisted = [...inputs.keys()].filter((id) => !listed.has(id));
  if (unlisted.length > 0) throw new Error(`${GROUPS}: add these inputs to a group: ${unlisted.join(", ")}`);

  lines.push("## Outputs", "", "| Output | Description |", "|--------|-------------|");
  for (const output of contract.outputs ?? []) lines.push(`| \`${output.id}\` | ${prose(output.description)} |`);
  lines.push("");
  return lines.join("\n");
}

const isMain = process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href;
if (isMain) {
  const text = render(parse(readFileSync(CONTRACT, "utf8")), JSON.parse(readFileSync(GROUPS, "utf8")));
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUTPUT, "utf8");
    } catch {
      // missing counts as stale
    }
    if (current !== text) {
      console.error(`${OUTPUT} is stale; run: node scripts/generate-inputs-doc.mjs`);
      process.exit(1);
    }
  } else {
    writeFileSync(OUTPUT, text);
  }
}
